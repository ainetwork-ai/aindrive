// Bundle ssh-server.ts (and the TypeScript lib it imports: the drive gate,
// slug resolution, SSO config) into one plain-Node ESM file that server.js can
// `import()`. server.js runs under Node without a TypeScript loader and the
// lib uses `@/` aliases and extensionless imports, so a bundle is the only way
// for the two to share one process. node_modules stay external (ssh2,
// better-sqlite3, pino, …) and so does lib/agents.js: the agent registry must be
// the very module instance server.js uses (it pins on globalThis, but keeping
// one instance avoids two copies of its code). Output: .ssh-server/ssh-server.mjs
// (gitignored; built by prebuild/predev and copied into the Docker image).
import { build } from "esbuild";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [resolve(root, "ssh-server.ts")],
  outfile: resolve(root, ".ssh-server/ssh-server.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "external",
  alias: { "@": root },
  sourcemap: "inline",
  logLevel: "warning",
  banner: { js: "// generated by scripts/build-ssh-server.mjs — do not edit" },
});
console.log("[build-ssh-server] wrote .ssh-server/ssh-server.mjs");
